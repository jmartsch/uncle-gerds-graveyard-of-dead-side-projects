// Progress lines from the server while a graveyard is dug, in German.
const SERVER_LINES_DE = [
  [/^Looking for (.+)'s public repos without a push in (\d+) days…$/, (m) => `Ich suche die öffentlichen Repos von ${m[1]} ohne Push seit ${m[2]} Tagen…`],
  [/^Looking for public repos without a push in (\d+) days…$/, (m) => `Ich suche öffentliche Repos ohne Push seit ${m[1]} Tagen…`],
  [/^Fetching (\d+) hand-picked repos…$/, (m) => `Ich hole ${m[1]} handverlesene Repos…`],
  [/^Exhuming (.+)…$/, (m) => `Ich grabe ${m[1]} aus…`],
  [/^Jev: revival (\S+), worth it (\S+), mood (.+)$/, (m) => `Jev: Wiederbelebung ${m[1]}, lohnt sich ${m[2]}, Laune ${STRINGS.de.moods[m[3]] || m[3]}`],
  [/^Jev is unavailable/, () => 'Jev ist nicht erreichbar, also gibt es für dieses hier keine Chancen.'],
  [/^Uncle Gerd has written his commentary\.$/, () => 'Onkel Gerd hat seinen Kommentar geschrieben.'],
  [/^Ollama is unavailable/, () => 'Ollama ist nicht erreichbar, also nimmt Onkel Gerd seine Ersatzsprüche.'],
  [/^Museum ready: (\d+) exhibits\.$/, (m) => `Fertig: ${m[1]} Gräber.`],
  [/^Not a single dead repo\./, () => 'Kein einziges totes Repo. Onkel Gerd ist fast enttäuscht.'],
  [/^Uncle Gerd has dug enough graves this hour\.$/, () => 'Onkel Gerd hat für diese Stunde genug Gräber geschaufelt.'],
  [/^The cemetery gate is crowded\.$/, () => STRINGS.de.gateCrowded],
  [/^That is not a valid GitHub username\.$/, () => STRINGS.de.invalidUser],
];

export function serverLine(msg) {
  if (lang !== 'de' || typeof msg !== 'string') return msg;
  for (const [pattern, german] of SERVER_LINES_DE) {
    const m = msg.match(pattern);
    if (m) return german(m);
  }
  return msg;
}

export function t(key, ...args) {
  const value = STRINGS[lang][key] ?? STRINGS.en[key];
  return typeof value === 'function' ? value(...args) : value;
}

// Fills every [data-i18n] (text), [data-i18n-html] (trusted HTML) and [data-i18n-<attr>] in the page.
export function translatePage(root = document) {
  document.documentElement.lang = lang;
  const page = PAGE[lang];
  for (const node of root.querySelectorAll('[data-i18n]')) node.textContent = page[node.dataset.i18n] ?? PAGE.en[node.dataset.i18n];
  for (const node of root.querySelectorAll('[data-i18n-html]')) node.innerHTML = page[node.dataset.i18nHtml] ?? PAGE.en[node.dataset.i18nHtml];
  for (const attr of ['aria-label', 'placeholder']) {
    const data = `data-i18n-${attr}`;
    for (const node of root.querySelectorAll(`[${data}]`)) node.setAttribute(attr, page[node.getAttribute(data)] ?? PAGE.en[node.getAttribute(data)]);
  }
}
