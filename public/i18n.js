// English and German. Uncle Gerd speaks plain English in English and like a grumpy German uncle in German.
export const LANGS = { en: 'English', de: 'Deutsch' };

function readLang() {
  const fromUrl = new URLSearchParams(location.search).get('lang');
  if (fromUrl in LANGS) return fromUrl;
  try {
    const saved = localStorage.getItem('ugm-lang');
    return saved in LANGS ? saved : 'en';
  } catch {
    return 'en';
  }
}

let lang = readLang();
export const getLang = () => lang;
export const locale = () => (lang === 'de' ? 'de-DE' : 'en-GB');

export function storeLang(next) {
  lang = next in LANGS ? next : 'en';
  try {
    localStorage.setItem('ugm-lang', lang);
  } catch {}
  const url = new URL(location.href);
  if (url.searchParams.has('lang')) {
    url.searchParams.set('lang', lang);
    history.replaceState(null, '', url);
  }
}

